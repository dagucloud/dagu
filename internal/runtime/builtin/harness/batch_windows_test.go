// The wrappers in these tests start a Node script that prints its
// arguments. npm installs agent CLIs as such wrappers around Node programs,
// which read their command line with the standard Windows rules.
const argDumpScript = "process.stdout.write(JSON.stringify(process.argv.slice(2)))\n"

// A wrapper generated by npm is replaced by the Node program it starts, so
// the prompt arrives whole, line breaks included, and cmd.exe never parses it.
func TestHarnessRunsNpmWrapperProgramDirectly(t *testing.T) {
	nodeDir := nodeDirForTest(t)
	binDir := t.TempDir()
	script := filepath.Join(binDir, "node_modules", "@scope", "tool", "bin", "cli.js")
	require.NoError(t, os.MkdirAll(filepath.Dir(script), 0o750))
	require.NoError(t, os.WriteFile(script, []byte(argDumpScript), 0o600))
	installShim(t, binDir, "npm-cmd-shim-9.cmd")
	marker := filepath.Join(t.TempDir(), "injected")
	prompt := injectionPrompt(marker) + "\nsecond line"

	stdout, err := runBatchHarness(t, "tool", prompt, binDir, nodeDir)
	require.NoError(t, err)
	assert.Equal(t, []string{prompt}, decodeArgs(t, stdout))
	assert.NoFileExists(t, marker)
}

// pnpm wraps a bin that is itself a batch file in "cmd /C", which drops the
// outer quotes of its command line and parses the rest again. That batch
// file runs in the wrapper's place, with its arguments quoted for cmd.exe.
func TestHarnessRunsBatchFileBehindPnpmWrapper(t *testing.T) {
	nodeDir := nodeDirForTest(t)
	binDir := t.TempDir()
	writeArgDumpBatch(t, filepath.Join(binDir, "node_modules", "@scope", "tool", "bin", "cli.cmd"))
	installShim(t, binDir, "pnpm-cmd-shim-batch.cmd")
	marker := filepath.Join(t.TempDir(), "injected")
	prompt := injectionPrompt(marker)
	systemDir := filepath.Join(os.Getenv("SystemRoot"), "System32")

	stdout, err := runBatchHarness(t, "tool", prompt, binDir, nodeDir, systemDir)
	require.NoError(t, err)
	assert.Equal(t, []string{prompt}, decodeArgs(t, stdout))
	assert.NoFileExists(t, marker)
}

// Any other batch file runs through cmd.exe with each argument quoted so
// that cmd.exe passes it on unchanged.
func TestHarnessQuotesArgumentsForOtherBatchFiles(t *testing.T) {
	nodeDir := nodeDirForTest(t)
	binDir := writeArgDumpWrapper(t)
	marker := filepath.Join(t.TempDir(), "injected")
	prompt := injectionPrompt(marker)

	stdout, err := runBatchHarness(t, "wrapper", prompt, binDir, nodeDir)
	require.NoError(t, err)
	assert.Equal(t, []string{prompt}, decodeArgs(t, stdout))
	assert.NoFileExists(t, marker)
}

func TestHarnessRejectsLineBreaksForOtherBatchFiles(t *testing.T) {
	nodeDir := nodeDirForTest(t)
	binDir := writeArgDumpWrapper(t)

	_, err := runBatchHarness(t, "wrapper", "first line\nsecond line", binDir, nodeDir)
	require.ErrorContains(t, err, "line breaks")
}

// injectionPrompt ends cmd.exe quoting before a chained command that would
// create marker, and names variables, all of which must arrive as plain text.
// With Go's default quoting, the inner quote closes cmd.exe's quoted region,
// so the command after "&" runs.
func injectionPrompt(marker string) string {
	return `say "hi & echo injected > ` + marker + ` & rem " %PATH% ^| <x> !OS!`
}

// writeArgDumpWrapper writes a hand-written wrapper, which is not one a
// package manager generates, and returns its directory.
func writeArgDumpWrapper(t *testing.T) string {
	t.Helper()
	binDir := t.TempDir()
	writeArgDumpBatch(t, filepath.Join(binDir, "wrapper.cmd"))
	return binDir
}

// writeArgDumpBatch writes a batch file at path that passes its arguments
// to the Node script beside it.
func writeArgDumpBatch(t *testing.T, path string) {
	t.Helper()
	dir := filepath.Dir(path)
	require.NoError(t, os.MkdirAll(dir, 0o750))
	require.NoError(t, os.WriteFile(filepath.Join(dir, "dump.js"), []byte(argDumpScript), 0o600))
	require.NoError(t, os.WriteFile(path, []byte("@node \"%~dp0\\dump.js\" %*\r\n"), 0o600))
}

// installShim copies the wrapper in testdata/shims named fixture to binDir
// as tool.cmd.
func installShim(t *testing.T, binDir, fixture string) {
	t.Helper()
	shim, err := os.ReadFile(filepath.Join("testdata", "shims", fixture))
	require.NoError(t, err)
	require.NoError(t, os.WriteFile(filepath.Join(binDir, "tool.cmd"), shim, 0o600))
}

func runBatchHarness(t *testing.T, binary, prompt string, pathDirs ...string) (string, error) {
	t.Helper()
	dag := &ir.DAG{
		Name:       "harness-batch",
		WorkingDir: t.TempDir(),
		Harnesses: ir.HarnessDefinitions{
			"custom": {
				Binary:     binary,
				PromptMode: ir.HarnessPromptModeArg,
				FlagStyle:  ir.HarnessFlagStyleGNULong,
			},
		},
	}
	step := ir.Step{
		Name:     "step1",
		Commands: []ir.CommandEntry{{Command: prompt}},
		ExecutorConfig: ir.ExecutorConfig{
			Type:   "harness",
			Config: map[string]any{"provider": "custom"},
		},
	}
	ctx := newHarnessTestContext(t, dag, step, "PATH="+strings.Join(pathDirs, string(os.PathListSeparator)))
	executor, err := newHarness(ctx, step)
	require.NoError(t, err)

	var stdout, stderr strings.Builder
	executor.SetStdout(&stdout)
	executor.SetStderr(&stderr)
	err = executor.Run(ctx)
	if err != nil {
		t.Logf("stderr: %s", stderr.String())
	}
	return stdout.String(), err
}

func nodeDirForTest(t *testing.T) string {
	t.Helper()
	node, err := exec.LookPath("node")
	if err != nil {
		t.Skip("node is not installed")
	}
	return filepath.Dir(node)
}

func decodeArgs(t *testing.T, stdout string) []string {
	t.Helper()
	var args []string
	require.NoError(t, json.Unmarshal([]byte(stdout), &args), "stdout: %s", stdout)
	return args
}
