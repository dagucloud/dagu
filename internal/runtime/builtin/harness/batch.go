// maxBatchCommandLine is the longest command line cmd.exe accepts, in
// UTF-16 code units.
const maxBatchCommandLine = 8191

var errBatchLineBreak = errors.New("cmd.exe cannot pass arguments that contain line breaks; " +
	"define a harness whose binary is the CLI's executable")

// adaptBatchCommand keeps cmd.exe from reinterpreting the arguments of a
// command whose binary is a Windows batch file. Windows runs batch files
// through cmd.exe, which parses the command line again: quotes and
// metacharacters in an argument can end it and run further commands, and
// %NAME% is expanded even inside quotes. A wrapper generated by npm or pnpm
// is replaced by the Node program it starts, or by the batch file it hands
// to cmd /C; any other batch file runs with its arguments quoted for
// cmd.exe. resolve looks a program up as the step's PATH does.
func adaptBatchCommand(cmd *exec.Cmd, resolve func(string) (string, error)) error {
	if goruntime.GOOS != "windows" || !isBatchFile(cmd.Path) {
		return nil
	}
	args := cmd.Args[1:]
	if content, err := os.ReadFile(cmd.Path); err == nil {
		if shim, ok := parseNodeShim(string(content)); ok {
			dir := filepath.Dir(cmd.Path)
			script := filepath.Join(dir, shim.script)
			switch {
			case shim.prog == "node":
				// Node splits its command line by the rules Go quotes for;
				// other runtimes may not.
				if program, stripJS, ok := shim.program(dir, resolve); ok {
					cmd.Args = append(append(append([]string{cmd.Args[0]}, shim.args...), script), args...)
					cmd.Path = program
					cmd.Env = shim.environ(cmd.Env, stripJS)
					return nil
				}
			case shim.runsBatchFile():
				// cmd /C drops the outer quotes of the line it is given and
				// parses the rest again, so no quoting survives the wrapper.
				cmd.Path = script
				cmd.Env = shim.environ(cmd.Env, shim.stripsJS(dir))
			}
		}
	}

	line, err := batchCommandLine(cmd.Path, args)
	if err != nil {
		return fmt.Errorf("harness: %s runs through cmd.exe: %w", filepath.Base(cmd.Path), err)
	}
	return setBatchCommandLine(cmd, line)
}

func isBatchFile(path string) bool {
	ext := strings.ToLower(filepath.Ext(path))
	return ext == ".cmd" || ext == ".bat"
}

// batchCommandLine builds a cmd.exe command line that runs script with args
// delivered unchanged. Each argument is quoted where cmd.exe would act on
// it, a double quote is doubled so the quoting stays balanced, and % in the
// script path or an argument is written as %%cd:~,% (an empty substring of
// %cd%) so that no variable expands. Line breaks end a cmd.exe command and
// cannot be passed.
func batchCommandLine(script string, args []string) (string, error) {
	if strings.Contains(script, `"`) {
		return "", fmt.Errorf("batch file path %q contains a double quote", script)
	}
	var b strings.Builder
	b.WriteString(`cmd.exe /e:ON /v:OFF /d /c ""`)
	b.WriteString(strings.ReplaceAll(script, "%", "%%cd:~,%"))
	b.WriteByte('"')
	for _, arg := range args {
		if strings.ContainsAny(arg, "\r\n") {
			return "", errBatchLineBreak
		}
		b.WriteByte(' ')
		appendBatchArg(&b, arg)
	}
	b.WriteByte('"')
	line := b.String()
	if n := utf16Len(line); n > maxBatchCommandLine {
		return "", fmt.Errorf("command line is %d characters; cmd.exe accepts at most %d", n, maxBatchCommandLine)
	}
	return line, nil
}

// utf16Len counts s in UTF-16 code units, the characters a Windows command
// line is measured in.
func utf16Len(s string) int {
	n := 0
	for _, r := range s {
		n += utf16.RuneLen(r)
	}
	return n
}

func appendBatchArg(b *strings.Builder, arg string) {
	// An empty argument would vanish, and a trailing backslash would escape
	// a closing quote added by the batch file itself.
	quote := arg == "" || strings.HasSuffix(arg, `\`)
	for _, r := range arg {
		if r < unicode.MaxASCII && !isAlphanumeric(r) && !strings.ContainsRune(`#$*+-./:?@\_`, r) || unicode.IsControl(r) {
			quote = true
			break
		}
	}
	if quote {
		b.WriteByte('"')
	}
	backslashes := 0
	for _, r := range arg {
		switch r {
		case '\\':
			backslashes++
			b.WriteRune(r)
			continue
		case '"':
			// Double the preceding backslashes so they stay literal.
			b.WriteString(strings.Repeat(`\`, backslashes))
			b.WriteByte('"')
		case '%':
			b.WriteString("%%cd:~,")
		}
		backslashes = 0
		b.WriteRune(r)
	}
	if quote {
		b.WriteString(strings.Repeat(`\`, backslashes))
		b.WriteByte('"')
	}
}

func isAlphanumeric(r rune) bool {
	return 'a' <= r && r <= 'z' || 'A' <= r && r <= 'Z' || '0' <= r && r <= '9'
}

// nodeShim is what a recognized npm or pnpm wrapper runs: prog.exe beside
// the wrapper when present, otherwise prog from PATH, with args, then
// script, then the wrapper's own arguments.
type nodeShim struct {
	prog   string
	args   []string
	script string
	// nodePath is prepended to NODE_PATH when set.
	nodePath string
	// stripJSLocal and stripJSPath report whether the wrapper removes .JS
	// from PATHEXT when it runs the program beside it or the one from PATH.
	stripJSLocal bool
	stripJSPath  bool
}

// nodeShimTemplate is a wrapper exactly as a generator writes it, with
// {prog}, {args}, {script}, and {nodePath} where the generated values go.
type nodeShimTemplate struct {
	text         string
	stripJSLocal bool
	stripJSPath  bool
}

// nodeShimTemplates covers npm's cmd-shim 3 (npm 6), 4 through 8, and 9,
// and pnpm's @zkochan/cmd-shim with and without NODE_PATH. A wrapper that
// matches none of them, for example one setting other variables, runs
// through cmd.exe instead.
var nodeShimTemplates = []nodeShimTemplate{
	{
		text: "@ECHO off\nSETLOCAL\nCALL :find_dp0\n\n" +
			"IF EXIST \"%dp0%\\{prog}.exe\" (\n  SET \"_prog=%dp0%\\{prog}.exe\"\n) ELSE (\n  SET \"_prog={prog}\"\n  SET PATHEXT=%PATHEXT:;.JS;=;%\n)\n\n" +
			"\"%_prog%\" {args} \"%dp0%\\{script}\" %*\nENDLOCAL\nEXIT /b %errorlevel%\n:find_dp0\nSET dp0=%~dp0\nEXIT /b\n",
		stripJSPath: true,
	},
	{
		// endLocal restores PATHEXT before the program starts, so neither
		// branch removes .JS for it.
		text: "@ECHO off\nGOTO start\n:find_dp0\nSET dp0=%~dp0\nEXIT /b\n:start\nSETLOCAL\nCALL :find_dp0\n\n" +
			"IF EXIST \"%dp0%\\{prog}.exe\" (\n  SET \"_prog=%dp0%\\{prog}.exe\"\n) ELSE (\n  SET \"_prog={prog}\"\n  SET PATHEXT=%PATHEXT:;.JS;=;%\n)\n\n" +
			"endLocal & goto #_undefined_# 2>NUL || title %COMSPEC% & \"%_prog%\" {args} \"%dp0%\\{script}\" %*\n",
	},
	{
		text: "@ECHO off\nGOTO start\n:find_dp0\nSET dp0=%~dp0\nEXIT /b\n:start\nSETLOCAL\nCALL :find_dp0\n\n" +
			"IF EXIST \"%dp0%\\{prog}.exe\" (\n  SET \"_prog=%dp0%\\{prog}.exe\"\n) ELSE (\n  SET \"_prog={prog}\"\n)\n\n" +
			"endLocal & goto #_undefined_# 2>NUL || title %COMSPEC% & set PATHEXT=%PATHEXT:;.JS;=;% & \"%_prog%\" {args} \"%dp0%\\{script}\" %*\n",
		stripJSLocal: true,
		stripJSPath:  true,
	},
	{
		text: "@SETLOCAL\n" +
			"@IF EXIST \"%~dp0\\{prog}.exe\" (\n  \"%~dp0\\{prog}.exe\" {args} \"%~dp0\\{script}\" %*\n" +
			") ELSE (\n  @SET PATHEXT=%PATHEXT:;.JS;=;%\n  {prog} {args} \"%~dp0\\{script}\" %*\n)\n",
		stripJSPath: true,
	},
	{
		text: "@SETLOCAL\n" +
			"@IF NOT DEFINED NODE_PATH (\n  @SET \"NODE_PATH={nodePath}\"\n) ELSE (\n  @SET \"NODE_PATH={nodePath};%NODE_PATH%\"\n)\n" +
			"@IF EXIST \"%~dp0\\{prog}.exe\" (\n  \"%~dp0\\{prog}.exe\" {args} \"%~dp0\\{script}\" %*\n" +
			") ELSE (\n  @SET PATHEXT=%PATHEXT:;.JS;=;%\n  {prog} {args} \"%~dp0\\{script}\" %*\n)\n",
		stripJSPath: true,
	},
}

var (
	nodeShimPlaceholder = regexp.MustCompile(`\\\{(prog|args|script|nodePath)\\\}`)
	nodeShimGroups      = map[string]string{
		"prog":     `([A-Za-z0-9_.-]+)`,
		"args":     `([^"%\n]*)`,
		"script":   `([^"%\n]+)`,
		"nodePath": `([^"%\n]+)`,
	}
	// shimArgPattern accepts the plain options a shebang line can add.
	shimArgPattern = regexp.MustCompile(`^[A-Za-z0-9_.=:/+,-]+$`)
	nodeShimRules  = compileNodeShimTemplates()
)

type nodeShimRule struct {
	template nodeShimTemplate
	pattern  *regexp.Regexp
	fields   []string
}

func compileNodeShimTemplates() []nodeShimRule {
	rules := make([]nodeShimRule, 0, len(nodeShimTemplates))
	for _, template := range nodeShimTemplates {
		var fields []string
		quoted := regexp.QuoteMeta(template.text)
		expr := nodeShimPlaceholder.ReplaceAllStringFunc(quoted, func(placeholder string) string {
			name := nodeShimPlaceholder.FindStringSubmatch(placeholder)[1]
			fields = append(fields, name)
			return nodeShimGroups[name]
		})
		rules = append(rules, nodeShimRule{
			template: template,
			pattern:  regexp.MustCompile("^" + expr + "$"),
			fields:   fields,
		})
	}
	return rules
}

// parseNodeShim recognizes a wrapper written by npm or pnpm.
func parseNodeShim(content string) (nodeShim, bool) {
	content = strings.ReplaceAll(content, "\r\n", "\n")
	for _, rule := range nodeShimRules {
		match := rule.pattern.FindStringSubmatch(content)
		if match == nil {
			continue
		}
		values := map[string]string{}
		consistent := true
		for i, field := range rule.fields {
			value := match[i+1]
			if previous, seen := values[field]; seen && previous != value {
				consistent = false
				break
			}
			values[field] = value
		}
		if !consistent {
			continue
		}
		args, ok := shimArgs(values["args"])
		if !ok {
			continue
		}
		return nodeShim{
			prog:         values["prog"],
			args:         args,
			script:       values["script"],
			nodePath:     values["nodePath"],
			stripJSLocal: rule.template.stripJSLocal,
			stripJSPath:  rule.template.stripJSPath,
		}, true
	}
	return nodeShim{}, false
}

// shimArgs splits the options between the program and the script. The
// generators separate them by one space, so an empty value stands for none.
func shimArgs(value string) ([]string, bool) {
	value = strings.TrimSpace(value)
	if value == "" {
		return nil, true
	}
	args := strings.Split(value, " ")
	for _, arg := range args {
		if !shimArgPattern.MatchString(arg) {
			return nil, false
		}
	}
	return args, true
}

// program returns the program the wrapper in dir starts and whether it
// removes .JS from PATHEXT for it. It reports false when that program is
// itself a batch file or a script.
func (s nodeShim) program(dir string, resolve func(string) (string, error)) (string, bool, bool) {
	if local, ok := s.localProgram(dir); ok {
		return local, s.stripJSLocal, true
	}
	resolved, err := resolve(s.prog)
	if err != nil || !strings.EqualFold(filepath.Ext(resolved), ".exe") {
		return "", false, false
	}
	return resolved, s.stripJSPath, true
}

// stripsJS reports whether the wrapper in dir removes .JS from PATHEXT
// before it starts its program.
func (s nodeShim) stripsJS(dir string) bool {
	if _, ok := s.localProgram(dir); ok {
		return s.stripJSLocal
	}
	return s.stripJSPath
}

// localProgram returns prog.exe beside the wrapper in dir, which the
// wrapper prefers to prog from PATH, and whether it exists.
func (s nodeShim) localProgram(dir string) (string, bool) {
	local := filepath.Join(dir, s.prog+".exe")
	info, err := os.Stat(local)
	return local, err == nil && info.Mode().IsRegular()
}

// runsBatchFile reports whether the wrapper hands its script to cmd /C, as
// pnpm writes for a bin that is itself a batch file.
func (s nodeShim) runsBatchFile() bool {
	return s.prog == "cmd" && slices.Equal(s.args, []string{"/C"}) && isBatchFile(s.script)
}

// environ applies the wrapper's environment changes to env.
func (s nodeShim) environ(env []string, stripJS bool) []string {
	env = append([]string(nil), env...)
	if s.nodePath != "" {
		nodePath := s.nodePath
		if existing, ok := lookupEnv(env, "NODE_PATH"); ok && existing != "" {
			nodePath += ";" + existing
		}
		env = setEnv(env, "NODE_PATH", nodePath)
	}
	if stripJS {
		if pathExt, ok := lookupEnv(env, "PATHEXT"); ok {
			env = setEnv(env, "PATHEXT", replaceFold(pathExt, ";.JS;", ";"))
		}
	}
	return env
}

// lookupEnv returns the last value of key, compared without case as
// Windows does.
func lookupEnv(env []string, key string) (string, bool) {
	for _, e := range slices.Backward(env) {
		name, value, ok := strings.Cut(e, "=")
		if ok && strings.EqualFold(name, key) {
			return value, true
		}
	}
	return "", false
}

func setEnv(env []string, key, value string) []string {
	out := env[:0]
	for _, entry := range env {
		name, _, ok := strings.Cut(entry, "=")
		if ok && strings.EqualFold(name, key) {
			continue
		}
		out = append(out, entry)
	}
	return append(out, key+"="+value)
}

// replaceFold replaces every occurrence of old in s, matching without case
// as cmd.exe substitution does.
func replaceFold(s, old, replacement string) string {
	var b strings.Builder
	for i := 0; i < len(s); {
		if len(s)-i >= len(old) && strings.EqualFold(s[i:i+len(old)], old) {
			b.WriteString(replacement)
			i += len(old)
			continue
		}
		b.WriteByte(s[i])
		i++
	}
	return b.String()
}
